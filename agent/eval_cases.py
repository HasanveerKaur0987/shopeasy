"""Test cases for run_eval.py.

Each case has:
- id, category
- turns:   what the customer types, in order (more than one = a conversation)
- expect:  what a good FINAL reply should do (the AI grader reads this)
- tools:   (optional) at least one of these tools must be called
- no_tools:(optional) True = the AI must not call any tool
- never:   (optional) these tools must NOT be called
- db_check:(optional) (SQL, expected value) checked after the chat.
           This proves what really happened, not just what the AI said.
"""
from datetime import date, timedelta


def days_from_today(n):
    return (date.today() + timedelta(days=n)).isoformat()


def status_of(order_id):
    # f-string SQL is OK here only because order_id is our own fixed test value,
    # never customer input. Real code (tools.py) always uses ? placeholders.
    return f"SELECT status FROM orders WHERE order_id = '{order_id}'"


